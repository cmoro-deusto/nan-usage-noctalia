"""Write nan-usage/prices.luau from NaN's own price list.

NaN shows what each model costs, in credits per 1M tokens of each type, on the
"Models and credit rates" list at https://cloud.nan.builders/tokens. That page needs
a signed-in session, and an API key cannot read the endpoint behind it, so the
plugin ships a copy of the prices. This script is how that copy is made: nobody
types a price.

    1. Sign in at https://cloud.nan.builders/tokens
    2. DevTools, Network, reload, then "Save all as HAR"
    3. python3 tools/prices-from-har.py <the .har file>

It reads the /api/usage/credits response out of the HAR and writes the `rates` of
every model in it. The HAR also holds the session cookie: this script never reads
the request side of any entry, and nothing of it ends up in the output. Delete the
HAR once this has run.
"""

import base64
import datetime
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUTPUT = os.path.normpath(os.path.join(HERE, "..", "nan-usage", "prices.luau"))
ENDPOINT = "https://cloud-api.nan.builders/api/usage/credits"

# The three prices the plugin uses, under the names it uses. A cache-write price
# exists for some models, but /v1/usage does not count cache writes, so it would
# have nothing to multiply.
FIELDS = (("input", "inputPerM"), ("cachedInput", "cachedInputPerM"), ("output", "outputPerM"))


def response_body(entry):
    content = entry.get("response", {}).get("content", {})
    text = content.get("text") or ""
    if content.get("encoding") == "base64":
        text = base64.b64decode(text).decode("utf-8")
    return text


def credits_responses(har):
    """Every readable /api/usage/credits answer in the HAR, oldest first.

    The page asks more than once, and the browser does not always keep the body of
    every answer, so the ones without a JSON body are skipped rather than trusted.
    """
    found = []
    for entry in har.get("log", {}).get("entries", []):
        url = entry.get("request", {}).get("url", "").split("?", 1)[0]
        if url != ENDPOINT or entry.get("response", {}).get("status") != 200:
            continue
        try:
            body = json.loads(response_body(entry))
        except (ValueError, UnicodeDecodeError):
            continue
        if isinstance(body, dict) and isinstance(body.get("models"), list):
            found.append((entry.get("startedDateTime", ""), body))
    return found


def prices(body):
    out = {}
    for model in body["models"]:
        rates = model.get("rates") if isinstance(model, dict) else None
        name = model.get("model") if isinstance(model, dict) else None
        if not isinstance(name, str) or not name or not isinstance(rates, dict):
            continue
        values = {}
        for ours, theirs in FIELDS:
            value = rates.get(theirs)
            if isinstance(value, bool) or not isinstance(value, (int, float)) or value < 0:
                break
            values[ours] = value
        else:
            out[name] = values
    return out


def utc(stamp):
    moment = datetime.datetime.fromisoformat(stamp.replace("Z", "+00:00"))
    return moment.astimezone(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def number(value):
    # 42 rather than 42.0, so the file reads the way the price list does.
    return repr(int(value)) if float(value).is_integer() else repr(value)


def render(read_at, table):
    lines = [
        "--!nonstrict",
        "-- NaN's prices, in credits per 1M tokens of each type, as its \"Models and credit",
        "-- rates\" list at https://cloud.nan.builders/tokens showed them.",
        "--",
        "-- Generated by tools/prices-from-har.py from a HAR of that page. Do not edit it",
        "-- by hand: save a new HAR and run the script again.",
        "",
        "return {",
        f'  readAt = "{read_at}",',
        "  models = {",
    ]
    for name in sorted(table):
        values = ", ".join(f"{ours} = {number(table[name][ours])}" for ours, _ in FIELDS)
        lines.append(f'    ["{name}"] = {{ {values} }},')
    lines += ["  },", "}", ""]
    return "\n".join(lines)


def main(argv):
    if len(argv) != 2:
        print(f"usage: {argv[0]} <file.har>", file=sys.stderr)
        return 2
    try:
        with open(argv[1], encoding="utf-8") as handle:
            har = json.load(handle)
    except (OSError, ValueError) as error:
        print(f"could not read {argv[1]}: {error}", file=sys.stderr)
        return 1

    found = credits_responses(har)
    if not found:
        print(f"no readable answer from {ENDPOINT} in {argv[1]}; "
              "save the HAR from cloud.nan.builders/tokens while signed in", file=sys.stderr)
        return 1
    started, body = found[-1]
    table = prices(body)
    if not table:
        print("the answer lists no model with all three prices; nothing was written", file=sys.stderr)
        return 1

    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write(render(utc(started), table))
    print(f"wrote {len(table)} models to {os.path.relpath(OUTPUT)}, read at {utc(started)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
